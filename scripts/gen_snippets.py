#!/usr/bin/env python3
"""Regenerate docs/CODE_SNIPPETS.md from docs/Android_Engineering_Playbook.docx.

The DOCX is the source of truth for the playbook, so snippets are extracted from it
rather than from the PDF: PDF extraction splits long code lines at page boundaries and
a vision pass over a rendered page misreads `IO` as `10` and `=` as `$` (see
learning/INCIDENTS.md, INCIDENT-001).

Requires python-docx:  pip install python-docx

Usage:
    python3 scripts/gen_snippets.py
Exit code 0 = snippets written and TOC anchors verified.
"""

import os
import re
import sys

try:
    from docx import Document
except ImportError:
    sys.exit('error: python-docx is required -> pip install python-docx')

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCX = os.path.join(REPO, 'docs', 'Android_Engineering_Playbook.docx')
OUT = os.path.join(REPO, 'docs', 'CODE_SNIPPETS.md')

# Titles in document order. If the playbook gains or loses a code block, update this list -
# the script asserts the count so a silent mismatch is impossible.
TITLES = [
    "Install the agent skills",
    "FeedViewModel and UiState",
    "Hilt AppModule",
    "Edge-to-edge insets",
    "Navigation 3 with NavDisplay",
    "OfflineFirstFeedRepository",
    "libs.versions.toml",
    "Convention plugin build-logic",
    "gradle.properties",
    "Release signing build.gradle.kts",
    "R8 config analyser",
    "ViewModel unit test with Turbine",
    "Test and build commands",
    "Headless dev loop with adb",
    "GitHub Actions pipeline",
    "Capacitor web-to-APK",
    "Official template package tree",
    "Official template ViewModel",
    "Feature recipe prompt",
    "AGENTS.md single-module template",
    "AGENTS.md multi-module template",
]


def is_code(paragraph):
    runs = [r for r in paragraph.runs if r.text.strip()]
    return bool(runs) and all(r.font.name == 'Consolas' for r in runs)


def collect(document):
    blocks, cur = [], None
    for p in document.paragraphs:
        if is_code(p):
            if cur is None:
                cur = []
            line, lines = '', []
            for r in p.runs:
                parts = r.text.split('\n')
                if len(parts) > 1:
                    for x in parts[:-1]:
                        lines.append(line + x)
                        line = ''
                    line += parts[-1]
                else:
                    line += r.text
            lines.append(line)
            cur.extend(lines)
        elif cur is not None:
            blocks.append(cur)
            cur = None
    if cur:
        blocks.append(cur)
    return blocks


def lang(body):
    if body.lstrip().startswith('# [App name]'):
        return 'markdown'
    if 'uses:' in body or 'runs-on:' in body:
        return 'yaml'
    if re.search(r'^\[versions\]|^\[libraries\]|^\[plugins\]', body, re.M):
        return 'toml'
    if re.search(r'^org\.gradle|^android\.|^kotlin\.daemon', body, re.M):
        return 'properties'
    if re.search(r'^# Google|^# a tight|^pip install|^npm |^\./gradlew|^android skills', body, re.M):
        return 'bash'
    if body.lstrip().startswith('app/src/main/java'):
        return 'text'
    return 'kotlin'


def anchor(title):
    a = title.lower()
    a = re.sub(r'[^a-z0-9 \-]', '', a)
    return a.strip().replace(' ', '-')


def main():
    if not os.path.exists(DOCX):
        sys.exit(f'error: missing {DOCX}')

    blocks = collect(Document(DOCX))
    if len(blocks) != len(TITLES):
        sys.exit(
            f'error: found {len(blocks)} code blocks but TITLES lists {len(TITLES)}.\n'
            'Update TITLES in scripts/gen_snippets.py to match the playbook.'
        )

    out = [
        '# Code snippets',
        '',
        'Every code, config and YAML block from the '
        '[Android Engineering Playbook](Android_Engineering_Playbook.pdf), extracted from the source '
        '`.docx` rather than the PDF.',
        '',
        '**Copy from here, not from the PDF.** PDF text extraction and OCR passes mangle monospace '
        'code - dropping `=`, turning `O` into `0`, splitting long lines across page breaks. These '
        'blocks are the exact bytes from the source document.',
        '',
        'Generated by `scripts/gen_snippets.py`. Do not edit by hand: edit the playbook and regenerate.',
        '',
        'Looking for a **library** rather than a snippet? See '
        '[FEATURE_RECIPES.md](FEATURE_RECIPES.md) - one verified repository per capability.',
        '',
        '## Contents',
        '',
    ]
    out += [f'{i}. [{t}](#{anchor(t)})' for i, t in enumerate(TITLES, 1)]
    out.append('')

    for title, lines in zip(TITLES, blocks):
        body = '\n'.join(lines)
        out += [f'## {title}', '', f'```{lang(body)}'] + lines + ['```', '']

    text = '\n'.join(out).rstrip() + '\n'

    heads = {anchor(h) for h in re.findall(r'^## (.+)$', text, re.M)}
    missing = [t for t in TITLES if anchor(t) not in heads]
    if missing:
        sys.exit(f'error: TOC anchors do not resolve: {missing}')
    if text.count('```') % 2:
        sys.exit('error: unbalanced code fences in generated output')

    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write(text)
    print(f'wrote {OUT} - {len(blocks)} blocks, {len(text.split())} words')


if __name__ == '__main__':
    main()
